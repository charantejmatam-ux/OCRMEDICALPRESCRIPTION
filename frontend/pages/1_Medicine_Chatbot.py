"""Medicine-only, DailyMed-grounded chatbot page."""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any

import requests
import streamlit as st
from dotenv import dotenv_values

PROJECT_ENV_FILE = Path(__file__).resolve().parents[1] / ".env"
_dotenv_config = dotenv_values(PROJECT_ENV_FILE, interpolate=False)
BACKEND_URL = (
    os.getenv("BACKEND_URL")
    or _dotenv_config.get("BACKEND_URL")
    or "http://localhost:8000"
)
del _dotenv_config

st.set_page_config(
    page_title="Medicine Chatbot",
    page_icon="💊",
    layout="wide",
)

st.title("Medicine Information Chatbot")
st.markdown(
    "Ask about a medicine's labeled uses, directions for age groups, warnings, "
    "or side effects. Answers are generated by **Gemma** using the "
    "specific U.S. DailyMed label you select."
)
st.warning(
    "This is not a clinician and cannot determine the right dose for a particular "
    "person. Age-, weight-, sex-, and condition-specific use must be confirmed "
    "with a doctor or pharmacist. Do not use this for emergencies."
)
st.caption(
    "Medicine-label search always uses public U.S. DailyMed. If GEMMA_API_KEY is "
    "configured, your question and selected label evidence are sent to Google's "
    "Gemma API; otherwise they are sent to local Ollama Gemma. A temporary cloud "
    "failure may also use local Ollama."
)
st.caption("Do not enter patient names or other personal identifying information.")

if "medicine_chat_labels" not in st.session_state:
    st.session_state["medicine_chat_labels"] = []
if "medicine_chat_messages" not in st.session_state:
    st.session_state["medicine_chat_messages"] = []


def show_error(response: requests.Response) -> None:
    try:
        detail: Any = response.json().get("detail")
    except ValueError:
        detail = response.text
    st.error(str(detail or f"Request failed with HTTP {response.status_code}."))


with st.form("medicine_label_search"):
    medicine_name = st.text_input(
        "Medicine name",
        max_chars=120,
        placeholder="For example, ibuprofen",
    )
    search_submitted = st.form_submit_button("Find DailyMed labels", type="primary")

if search_submitted:
    if len(medicine_name.strip()) < 2:
        st.warning("Enter at least two characters for a medicine name.")
    else:
        try:
            response = requests.get(
                f"{BACKEND_URL}/medicine-chat/labels",
                params={"drug_name": medicine_name.strip()},
                timeout=15,
            )
            if response.status_code == 200:
                st.session_state["medicine_chat_labels"] = response.json().get("labels", [])
                st.session_state["medicine_chat_messages"] = []
                if not st.session_state["medicine_chat_labels"]:
                    st.info(
                        "DailyMed returned no matching labels. Check the spelling or try "
                        "the generic name."
                    )
            else:
                show_error(response)
        except requests.RequestException as exc:
            st.error(f"Could not reach the chatbot backend: {exc}")

labels: list[dict[str, Any]] = st.session_state["medicine_chat_labels"]
selected_label: dict[str, Any] | None = None
if labels:
    st.subheader("Choose the exact product label")
    selected_index = st.selectbox(
        "DailyMed labels",
        options=list(range(len(labels))),
        format_func=lambda index: (
            f"{labels[index]['title']}"
            + (
                f" — published {labels[index]['published_date']}"
                if labels[index].get("published_date")
                else ""
            )
        ),
    )
    selected_label = labels[selected_index]
    st.link_button(
        "Open selected official label",
        f"https://dailymed.nlm.nih.gov/dailymed/drugInfo.cfm?setid={selected_label['setid']}",
    )

    with st.form("medicine_question"):
        question = st.text_area(
            "Ask a medicine question",
            max_chars=1000,
            placeholder=(
                "What is this medicine used for? What side effects are listed? "
                "What does the label say about use in children?"
            ),
        )
        question_submitted = st.form_submit_button("Ask Gemma", type="primary")

    if question_submitted:
        if not question.strip():
            st.warning("Enter a medicine question.")
        else:
            with st.spinner("Retrieving the label and asking Gemma..."):
                try:
                    response = requests.post(
                        f"{BACKEND_URL}/medicine-chat/ask",
                        json={
                            "setid": selected_label["setid"],
                            "question": question.strip(),
                        },
                        timeout=660,
                    )
                    if response.status_code == 200:
                        answer = response.json()
                        st.session_state["medicine_chat_messages"].append(
                            {
                                "question": question.strip(),
                                "answer": answer,
                            }
                        )
                    else:
                        show_error(response)
                except requests.RequestException as exc:
                    st.error(f"Could not reach the chatbot backend: {exc}")

    for item in st.session_state["medicine_chat_messages"]:
        with st.chat_message("user"):
            st.write(item["question"])
        with st.chat_message("assistant"):
            answer = item["answer"]
            st.markdown(answer["answer"])
            st.caption(
                f"Model: {answer['model']} · "
                f"Label sections: {', '.join(answer['sections']) or 'none listed'}"
            )
            st.markdown(f"**Source:** [{answer['source_title']}]({answer['source_url']})")
            st.caption(answer["disclaimer"])
